/** هل النص صالح للترميز Code 39؟ */
export function isCode39Valid(text: string): boolean {
  return /^[0-9A-Z\-. $/+%]*$/.test(text.toUpperCase())
}

/**
 * ترميز نص إلى سلسلة أصفار/آحاد (1 = قضيب، 0 = فراغ) — مع علامتي بداية/نهاية *.
 * يرمي خطأ عند وجود محارف غير مدعومة.
 */
export function encodeCode39(text: string): string {
  const up = text.toUpperCase()
  if (!isCode39Valid(up)) {
    throw new Error(`محارف غير مدعومة في الباركود Code 39: ${text}`)
  }
  const chars = `*${up}*`.split('')
  const bits: string[] = []
  for (const c of chars) {
    const pattern = CODE39_TABLE[c]
    if (!pattern) throw new Error(`محرف غير مدعوم في Code 39: ${c}`)
    bits.push(pattern)
  }
  // فاصل وحدة واحدة بين المحارف
  return bits.join('0')
}

/** عرض كل قضيب/فراغ بوحدات (لسلسلة الترميز) — لرسم SVG أو إرسالها للطابعة */
export function code39Bars(bits: string): number[] {
  const runs: number[] = []
  let cur = 1
  for (let i = 1; i < bits.length; i++) {
    if (bits[i] === bits[i - 1]) cur++
    else {
      runs.push(cur)
      cur = 1
    }
  }
  runs.push(cur)
  return runs
}
